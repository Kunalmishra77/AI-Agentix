#!/usr/bin/env bash
# AI Agentix — pull and deploy on the VPS, without downtime.
#
#   APP_DIR=/var/www/ai-agentix BRANCH=master PM2_APP=<name from `pm2 ls`> bash deploy/deploy.sh
#
# What it does (stops at the first error, live site untouched until the swap):
#   1. checks Node >= 20, a clean git tree, and that server/.env exists
#   2. git pull --ff-only of $BRANCH
#   3. server: npm ci, tests, re-embeds the knowledge base if OPENAI_API_KEY is set
#   4. frontend: npm ci, builds into dist-next/, then swaps it with dist/ (old kept as dist-prev/)
#   5. restarts the API with pm2 and checks /api/health and the home page
# Roll back the website: mv frontend/dist frontend/dist-bad && mv frontend/dist-prev frontend/dist
set -euo pipefail

APP_DIR="${APP_DIR:?set APP_DIR to the repository folder on the VPS}"
BRANCH="${BRANCH:-master}"
PM2_APP="${PM2_APP:?set PM2_APP to the API process name shown by pm2 ls}"
SITE_URL="${SITE_URL:-https://ai-agentix.com}"
API_PORT="${API_PORT:-5000}"

say() { printf '\n\033[1;33m▶ %s\033[0m\n' "$*"; }

say "Checks"
node -e 'process.exit(+process.versions.node.split(".")[0] >= 20 ? 0 : 1)' || { echo "Node 20+ required (found $(node -v))"; exit 1; }
cd "$APP_DIR"
[ -f server/.env ] || { echo "server/.env missing — copy server/.env.example and fill it in"; exit 1; }
git checkout -- server/src/knowledge.json 2>/dev/null || true   # regenerated by every deploy
if [ -n "$(git status --porcelain --untracked-files=no)" ]; then
  echo "Local changes on the server (not overwriting them):"; git status --short; exit 1
fi

say "Pull $BRANCH"
git fetch origin "$BRANCH"
git checkout "$BRANCH"
git pull --ff-only origin "$BRANCH"
git log --oneline -1

say "API server"
cd "$APP_DIR/server"
npm ci --no-audit --no-fund          # dev deps include esbuild (knowledge-base build)
npm test
LEADS_DIR_VALUE="$(grep -E '^LEADS_DIR=' .env | cut -d= -f2- || true)"
if [ -n "$LEADS_DIR_VALUE" ]; then mkdir -p "$LEADS_DIR_VALUE" && chmod 700 "$LEADS_DIR_VALUE"; fi
if grep -qE '^OPENAI_API_KEY=.+' .env; then
  npm run build:kb && npm run embed      # embeddings must match the new knowledge.json
else
  npm run build:kb                        # free rule-based assistant: no embeddings needed
fi

say "Website build (into dist-next, live dist untouched)"
cd "$APP_DIR/frontend"
npm ci --no-audit --no-fund
rm -rf dist-next
OUT_DIR=dist-next npm run build
[ -f dist-next/index.html ] && [ -f dist-next/sitemap.xml ] || { echo "build output incomplete"; exit 1; }

say "Swap"
rm -rf dist-prev
[ -d dist ] && mv dist dist-prev
mv dist-next dist

say "Restart API ($PM2_APP)"
pm2 reload "$PM2_APP" --update-env
sleep 3

say "Verify"
curl -fsS "http://127.0.0.1:${API_PORT}/api/health" && echo
curl -fsS -o /dev/null -w "home %{http_code}\n" "$SITE_URL/"
curl -fsS -o /dev/null -w "thank-you %{http_code}\n" "$SITE_URL/thank-you"
curl -fsS "$SITE_URL/sitemap.xml" | head -3
pm2 status "$PM2_APP"
echo; echo "Deployed $(git -C "$APP_DIR" rev-parse --short HEAD). Now test a form on the live site."
